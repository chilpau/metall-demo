/* Нормализация для поиска: регистр, ё, латиница → кириллица
   (похожие буквы и транслит: 09g2s, 12x18h10t и т.п.) */
window.normalizeQuery = (() => {
  const LATIN = { a: 'а', b: 'в', c: 'с', e: 'е', g: 'г', h: 'н', k: 'к', m: 'м', n: 'н', o: 'о', p: 'р', s: 'с', t: 'т', x: 'х', y: 'у' };
  return (s) => s.toLowerCase().replace(/ё/g, 'е').replace(/[abceghkmnopstxy]/g, (ch) => LATIN[ch]);
})();
